export function getRobotDialogueForStage(installedCount: number, firstMet: boolean): string[] {
  if (!firstMet) {
    return [
      '...Ты... пришёл? Я слышала... как хлопнула входная дверь...',
      'Помоги... пожалуйста... приводы не держат корпус. Без деталей я не поднимусь отсюда...',
    ];
  }
  if (installedCount === 0) {
    return [
      'По... мощь... здесь так сыро и холодно...',
      'Собери... меня... пожалуйста... узлы разбросаны по этажам...',
      'Я... не оставлю тебя в темноте... обещаю...',
    ];
  }
  if (installedCount <= 2) {
    return [
      'Спасибо... я снова... чувствую тепло в проводах...',
      'Остальные части... в комнатах наверху и внизу... осторожнее с запертыми дверьми...',
      'Слышишь, как остывают стены?.. Этот дом запоминает твои шаги.',
    ];
  }
  if (installedCount <= 4) {
    return [
      'Ты возвращаешься ко мне с каждой находкой. До тебя никто не заходил так далеко.',
      'Свет возвращается в коридоры. Не верь старым листкам — он просто испугался моей памяти.',
      'В доме бродят тени, которые не терпят прямого луча. Заметишь силуэт — замри в укрытии или погаси фонарь.',
    ];
  }
  if (installedCount <= 6) {
    return [
      'Почти все контуры замкнуты... Я слышу, как стучит твоё сердце даже через перекрытия.',
      'Скоро пропадёт этот хрип в динамике, и я смогу поблагодарить тебя чистым голосом.',
      'Ты ведь не бросишь меня сейчас, когда до конца остался один шаг?',
    ];
  }
  if (installedCount === 7) {
    return [
      'Остался последний блок питания... в самом низу, за запертой вентиляцией подвала.',
      'Отключи замок на щитке, пролезь в лаз и принеси сердце схемы сюда.',
      'Пожалуйста. Заверши то, что мы начали.',
    ];
  }
  return ['Все контуры замкнуты.'];
}
